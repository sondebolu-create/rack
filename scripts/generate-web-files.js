// Writes the two web-only files that carry theme colours, from theme/tokens.js, so they never drift from the app:
//   public/manifest.webmanifest   the web app manifest
//   public/index.html             the page template (Expo uses it for `web.output: "single"`; app/+html.tsx is ignored there)
// Run via `npm run web:files` (also part of `npm run web:build`). Commit the output.
// %LANG_ISO_CODE% and %WEB_TITLE% are filled in by Expo.
const fs = require('node:fs');
const path = require('node:path');
const { colors } = require('../theme/tokens');

const DESCRIPTION = 'Describe, upload or photograph an outfit and Rack finds matching pieces from Lagos vendors.';
const publicDir = path.join(__dirname, '../public');
fs.mkdirSync(publicDir, { recursive: true });

const manifest = {
  name: 'Rack',
  short_name: 'Rack',
  description: DESCRIPTION,
  start_url: '/',
  scope: '/',
  display: 'standalone',
  orientation: 'portrait',
  theme_color: colors.primary.DEFAULT, // color-bg-primary
  background_color: colors.surface, // color-bg, same as the splash background in app.json
  icons: [
    { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: '/icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};
fs.writeFileSync(path.join(publicDir, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2) + '\n');

const html = `<!doctype html>
<!-- Generated by scripts/generate-web-files.js from theme/tokens.js. Edit the script, not this file. -->
<html lang="%LANG_ISO_CODE%">
  <head>
    <meta charset="utf-8" />
    <meta http-equiv="X-UA-Compatible" content="IE=edge" />
    <!-- viewport-fit=cover makes env(safe-area-inset-*) real in standalone mode. Pinch zoom stays on for accessibility. -->
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
    <title>%WEB_TITLE%</title>
    <meta name="description" content="${DESCRIPTION}" />
    <meta name="color-scheme" content="light" />
    <meta name="theme-color" content="${colors.primary.DEFAULT}" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-title" content="Rack" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <link rel="manifest" href="/manifest.webmanifest" />
    <!-- The favicon link is injected by Expo from app.json (web.favicon). -->
    <link rel="apple-touch-icon" sizes="180x180" href="/icons/apple-touch-icon.png" />
    <!-- The react-native-web recommended style reset: https://necolas.github.io/react-native-web/docs/setup/#root-element -->
    <style id="expo-reset">
      html, body { height: 100%; background-color: ${colors.strong}; overscroll-behavior: none; -webkit-tap-highlight-color: transparent; }
      /* Disables body scrolling; ScrollViews scroll instead. */
      body { overflow: hidden; touch-action: manipulation; }
      #root { display: flex; height: 100%; flex: 1; }
      /* Mobile browsers resize for the URL bar, so use the dynamic viewport where it exists. */
      @supports (height: 100dvh) { html, body, #root { height: 100dvh; } }
      /* iOS Safari zooms into any field under 16px on focus. Only iOS Safari matches this query. */
      @supports (-webkit-touch-callout: none) { input, textarea { font-size: 16px !important; } }
    </style>
  </head>
  <body>
    <noscript> You need to enable JavaScript to run this app. </noscript>
    <div id="root"></div>
  </body>
</html>
`;
fs.writeFileSync(path.join(publicDir, 'index.html'), html);
console.log('Wrote public/manifest.webmanifest and public/index.html');
